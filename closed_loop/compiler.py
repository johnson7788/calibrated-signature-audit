@dataclass
class TaskParams:
    magnitude_threshold: float = 1.0
    sign_consistency_min: float = 5 / 6
    pair_group_cols: list[str] = field(default_factory=lambda: ["donor_id", "specimen"])
    condition_treatment: str = "UNC106238"
    condition_control: str = "none"
    covariates: list[str] = field(default_factory=lambda: ["donor", "condition", "composition(library-size proxy)"])
    overlap_note: str = "high-expression proxy (single-dataset; see limitations)"
    fallback_reason: str = ""


def _clamp(value, lo, hi, name: str, dflt: float) -> float:
    try:
        v = float(value)
    except (TypeError, ValueError):
        return dflt
    return v if lo <= v <= hi else dflt


def extract_params(instruction_text: str, llm: LLMClient | None = None, design_cols: list[str] | None = None) -> TaskParams:
    """从 instruction 提取任务参数。LLM 输出 JSON → 静态校验 → 越界回退默认。

    结构化参数（pair_group_cols 配对键）不由 LLM 提取——它是数据 schema 的属性，
    由 prepared design 的列确定（规格书第 4 节），LLM 只补 instruction 里的
    数值/名称/协变量（"模板优先、LLM 仅补缝隙"）。"""
    params = TaskParams()
    if design_cols:
        missing = [c for c in params.pair_group_cols if c not in design_cols]
        if missing:
            params.fallback_reason = f"pair group cols not in design: {missing}"
    if llm is None:
        return params
    prompt = (
        "You are a research-workflow compiler. Extract structured task parameters from the "
        "instruction below. Return ONLY a JSON object with these keys:\n"
        '{"magnitude_threshold": <float, e.g. 1.0 in "|mean log2 fold change| >= 1.0">,\n'
        ' "sign_consistency_min": <float, e.g. 5/6 as fraction>,\n'
        ' "condition_treatment": <string, the intervention condition name>,\n'
        ' "condition_control": <string, the baseline condition name>,\n'
        ' "pair_group_cols": <list[str], columns defining donor-pair groups>,\n'
        ' "covariates": <list[str], sensitivity-analysis covariates>}\n'
        "Tie every value to explicit wording in the instruction; if something is absent use null.\n\n"
        f"INSTRUCTION:\n{instruction_text[:6000]}"
    )
    raw = llm.complete(prompt)
    try:
        data = json.loads(re.sub(r"^```(json)?|```$", "", raw.strip(), flags=re.M))
    except json.JSONDecodeError:
        params.fallback_reason = "LLM output not JSON"
        return params
    if not isinstance(data, dict):
        params.fallback_reason = "LLM output not an object"
        return params

    params.magnitude_threshold = _clamp(data.get("magnitude_threshold"), 0.01, 10.0, "magnitude", 1.0)
    params.sign_consistency_min = _clamp(data.get("sign_consistency_min"), 0.0, 1.0, "sign", 5 / 6)
    t = str(data.get("condition_treatment") or "").strip()
    c = str(data.get("condition_control") or "").strip()
    if t and c and t != c:
        params.condition_treatment, params.condition_control = t, c
    else:
        params.fallback_reason += ("; conditions unclear" if params.fallback_reason else "conditions unclear")
    cols = data.get("pair_group_cols")
    # 忽略 LLM 的 pair_group_cols：配对键由 design schema 决定（静默忽略，不算回退）
    covs = data.get("covariates")
    if isinstance(covs, list) and all(isinstance(x, str) for x in covs):
        params.covariates = [str(x) for x in covs]
    return params


