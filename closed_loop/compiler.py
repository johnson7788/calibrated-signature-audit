def static_check(script: str) -> list[str]:
    """静态检查：语法 + 敏感操作。返回错误列表（空=通过）。"""
    errors: list[str] = []
    try:
        tree = ast.parse(script)
    except SyntaxError as exc:
        return [f"syntax error: {exc}"]
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            fname = ""
            if isinstance(node.func, ast.Name):
                fname = node.func.id
            elif isinstance(node.func, ast.Attribute):
                fname = node.func.attr
            if fname in {"eval", "exec", "system", "popen", "subprocess"}:
                errors.append(f"forbidden call: {fname}")
    if "import os" in script or "import subprocess" in script or "import sys" in script:
        errors.append("imports beyond pandas/numpy/scipy/sklearn/statsmodels/Path/json not allowed")
    return errors


def render_script(params: TaskParams, results_path: str | Path) -> str:
    return TEMPLATE.format(
        params=json.dumps(asdict(params), ensure_ascii=False, indent=2),
        prepared_dir=str(ROOT / "data" / "prepared"),
        results_path=str(results_path),
    )


def compile_task(
    instruction_text: str,
    results_path: str | Path,
    llm: LLMClient | None = None,
    out_name: str = "analysis_generated.py",
) -> Path:
    """完整编译流程：提取参数 → 渲染 → 静态检查 → 写出脚本。"""
    design_path = ROOT / "data" / "prepared" / "E-MTAB-8316.design.json"
    design_cols: list[str] = []
    if design_path.exists():
        design = json.loads(design_path.read_text(encoding="utf-8"))
        design_cols = list(design[0].keys()) if design else []
    params = extract_params(instruction_text, llm, design_cols=design_cols)
    script = render_script(params, results_path)
    errors = static_check(script)
    if errors:
        raise RuntimeError(f"static check failed: {errors}")
    GENERATED.mkdir(parents=True, exist_ok=True)
    out = GENERATED / out_name
    out.write_text(script, encoding="utf-8")
    return out


